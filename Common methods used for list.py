numbers = [1,2,3,4,5,6]
#append method
numbers.append(6)
print(numbers)
#extent method
number = [7,8,9]
numbers.extent(number)
print(numbers)
#insert method
numbers.insert(2,2.5)
print(numbers)
#remove method
numbers.remove(8)
print(numbers)
#pop method
numbers.pop(2)
print(numbers)
#clear list
numbers.clear()
print(numbers)
#Sort method
number1 = [2,3,5,6,1,7]
number1.sort()
print(number1)
#sorted method
numbers = [19, 2, 35, 1, 67, 41]
sorted_numbers = sorted(numbers)
print(numbers)
print(sorted_numbers)
#Reverse method
sorted_numbers.reverse()
print(sorted_numbers)
